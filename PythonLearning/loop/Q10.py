"""

Question 9 – Loop Through a List

Write a program that prints each item from this list:

fruits = ["Apple", "Banana", "Mango", "Orange"]

Expected output:

Apple
Banana
Mango
Orange

Requirements:
Use a for loop.
Do not use indexes.
Directly iterate over the list

"""

fruits = ["Apple", "Banana", "Mango", "Orange"]
for name in fruits:
    print(name)