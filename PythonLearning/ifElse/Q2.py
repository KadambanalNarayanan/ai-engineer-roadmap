"""
Write a program that:

Creates a variable:
temperature = 15
If the temperature is 20 or higher, print:
It's a warm day.
Otherwise, print:
It's a cool day.
Requirements
Use if...else.
Use the comparison operator >=.
Do not use elif.

"""

temperature = 15
if temperature >= 20:
    print("It's a warm day")
else:
    print("It's a cool day")
